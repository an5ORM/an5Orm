  private getGoFilterType(field: Field): string {
    const lower = field.type.toLowerCase();
    if (['datetime', 'datetime2', 'smalldatetime', 'date', 'datetimeoffset', 'timestamp'].includes(lower)) {
      return 'DateTimeFilter';
    }
    if (['bool', 'boolean', 'bit'].includes(lower)) {
      return 'BoolFilter';
    }
    if (['int', 'integer', 'smallint', 'tinyint'].includes(lower)) {
      return 'IntFilter';
    }
    if (['bigint', 'long', 'float', 'real', 'double', 'decimal', 'numeric', 'money'].includes(lower)) {
      return 'NumberFilter';
    }
    return 'StringFilter';
  }

