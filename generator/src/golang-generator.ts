  // ─── An5DbContext ──────────────────────────────────────────────────────────

  private generateDbContext(models: Model[]): string {
    let content = `// An5DbContext represents the main ORM database context.\ntype An5DbContext struct {\n\tDB      *sql.DB\n\tDialect Dialect\n`;

    for (const model of models) {
      const name = this.capitalize(model.name);
      content += `\t${name}s *TableClient[${model.name}]\n`;
      content += `\t${name}  *TableClient[${model.name}]\n`;
    }

    content += `}

// NewAn5DbContext initializes the ORM context (defaults to MSSQL dialect).
func NewAn5DbContext(db *sql.DB) *An5DbContext {
\treturn NewAn5DbContextWithConnStr(db, "")
}

// NewAn5DbContextWithConnStr initializes the ORM context with dialect detection.
func NewAn5DbContextWithConnStr(db *sql.DB, connStr string) *An5DbContext {
\td := detectDialect(connStr)
\tctx := &An5DbContext{DB: db, Dialect: d}
`;
    for (const model of models) {
      const name = this.capitalize(model.name);
      content += `\tclient${name} := NewTableClient[${model.name}](db, "${model.schemaName}.${model.tableName}", d)\n`;
      content += `\tctx.${name}s = client${name}\n`;
      content += `\tctx.${name}  = client${name}\n`;
    }
    content += `\treturn ctx\n}\n\n`;

    return content;
  }

